#!/usr/bin/env python3
"""Module registry and layering check.

Reads every ``__manifest__.py`` in the repository and
``registry/classification.json`` (hand-maintained layer and disposition per
module), then either writes ``registry.yaml`` or checks it.

    python3 scripts/module_registry.py --write   # regenerate registry.yaml
    python3 scripts/module_registry.py --check   # CI: fail on drift

``--check`` fails when:
  * a module on disk is not classified, or a classified module is gone;
  * a module depends on a module in a higher layer and the pair is not listed
    in ``known_violations`` (so existing debt is tolerated, new debt is not);
  * a listed known violation no longer exists (delete it from the list);
  * ``registry.yaml`` differs from what ``--write`` would produce.

Standard library only, so it runs before anything is installed.
"""
import argparse
import ast
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CLASSIFICATION = ROOT / "registry" / "classification.json"
OUTPUT = ROOT / "registry.yaml"
SKIP_PARTS = {".git", "node_modules"}
OPEN_LAYERS = {"internal", "venture"}  # may depend on anything


def find_modules():
    modules = {}
    for manifest in sorted(ROOT.rglob("__manifest__.py")):
        if SKIP_PARTS & set(manifest.parts):
            continue
        data = ast.literal_eval(manifest.read_text(encoding="utf-8"))
        folder = manifest.parent
        py_lines = 0
        for f in folder.rglob("*.py"):
            py_lines += len(f.read_text(encoding="utf-8", errors="ignore").splitlines())
        modules[folder.name] = {
            "path": folder.relative_to(ROOT).as_posix(),
            "title": str(data.get("name", "")).strip(),
            "version": str(data.get("version", "")),
            "license": str(data.get("license", "")),
            "application": bool(data.get("application", False)),
            "depends": list(data.get("depends", [])),
            "python_lines": py_lines,
            "test_files": len(list(folder.glob("tests/test_*.py"))),
            "access_csv": (folder / "security" / "ir.model.access.csv").exists(),
        }
    return modules


def violations(modules, cls):
    rank = {name: i for i, name in enumerate(cls["layers"])}
    found = []
    for name, mod in modules.items():
        layer = cls["modules"].get(name, {}).get("layer")
        if layer is None:
            continue
        for dep in mod["depends"]:
            dep_layer = cls["modules"].get(dep, {}).get("layer")
            if dep_layer is None:  # standard Odoo module
                continue
            if dep_layer in OPEN_LAYERS and layer not in OPEN_LAYERS:
                found.append(f"{name} -> {dep}")
            elif layer not in OPEN_LAYERS and rank[dep_layer] > rank[layer]:
                found.append(f"{name} -> {dep}")
    return sorted(found)


def q(value):
    return json.dumps(value, ensure_ascii=False)


def render(modules, cls, viol):
    out = [
        "# GENERATED by scripts/module_registry.py --write. Do not edit by hand.",
        "# Edit registry/classification.json or the module manifests instead.",
        "# Dispositions are proposals until approved in",
        "# docs/erp/project/DECISION_REGISTER.md.",
        "",
        f"layers: {q(cls['layers'])}",
        f"module_count: {len(modules)}",
        "layering_violations:",
    ]
    out += [f"  - {q(v)}" for v in viol] or ["  []"]
    if not viol:
        out[-2:] = ["layering_violations: []"]
    out.append("modules:")
    order = {name: i for i, name in enumerate(cls["layers"])}
    def key(item):
        return (order[cls["modules"][item[0]]["layer"]], item[0])
    for name, mod in sorted(modules.items(), key=key):
        c = cls["modules"][name]
        local = [d for d in mod["depends"] if d in modules]
        std = [d for d in mod["depends"] if d not in modules]
        out += [
            f"  {name}:",
            f"    layer: {c['layer']}",
            f"    disposition: {c['disposition']}",
            f"    path: {mod['path']}",
            f"    title: {q(mod['title'])}",
            f"    version: {q(mod['version'])}",
            f"    license: {q(mod['license'])}",
            f"    application: {str(mod['application']).lower()}",
            f"    depends_local: {q(local)}",
            f"    depends_standard: {q(std)}",
            f"    python_lines: {mod['python_lines']}",
            f"    test_files: {mod['test_files']}",
            f"    access_csv: {str(mod['access_csv']).lower()}",
            f"    note: {q(c.get('note', ''))}",
        ]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true")
    group.add_argument("--check", action="store_true")
    args = parser.parse_args()

    cls = json.loads(CLASSIFICATION.read_text(encoding="utf-8"))
    modules = find_modules()
    errors = []

    for name in sorted(set(modules) - set(cls["modules"])):
        errors.append(f"unclassified module: {name} (add it to registry/classification.json)")
    for name in sorted(set(cls["modules"]) - set(modules)):
        errors.append(f"classified but not on disk: {name}")
    for name, c in cls["modules"].items():
        if c.get("layer") not in cls["layers"]:
            errors.append(f"{name}: unknown layer {c.get('layer')!r}")
    if errors:
        print("\n".join("x " + e for e in errors))
        return 1

    viol = violations(modules, cls)
    known = sorted(cls.get("known_violations", []))
    text = render(modules, cls, viol)

    if args.write:
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}: {len(modules)} modules, "
              f"{len(viol)} layering violation(s)")
        for v in viol:
            print("  ", v, "" if v in known else "(NOT in known_violations)")
        return 0

    for v in viol:
        if v not in known:
            errors.append(f"new layering violation: {v}")
    for v in known:
        if v not in viol:
            errors.append(f"known violation is fixed, remove it from the list: {v}")
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current != text:
        errors.append("registry.yaml is out of date: run "
                      "python3 scripts/module_registry.py --write")
    if errors:
        print("\n".join("x " + e for e in errors))
        return 1
    print(f"registry ok: {len(modules)} modules, {len(known)} known layering violation(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
