export type Key = keyof typeof dict.en;

export function translate(lang: Lang, key: Key | string): string {
  const d = dict[lang] as Record<string, string>;
  return d[key] ?? (dict.en as Record<string, string>)[key] ?? key;
}

export const stateLabel = (lang: Lang, state: string | false | null | undefined) =>
  state ? translate(lang, `state_${state}`) : '—';

export const tierLabel = (lang: Lang, tier: string | false | null | undefined) =>
  tier ? translate(lang, `tier_${tier}`) : translate(lang, 'tier_standard');

export const I18nContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: 'en', setLang: () => {},
});

export function useT() {
  const { lang, setLang } = useContext(I18nContext);
  return { lang, setLang, t: (k: Key | string) => translate(lang, k), dir: lang === 'ar' ? 'rtl' : 'ltr' as const };
}
